-- 3. Проверка: выборка всех данных из основных таблиц

-- 3.1. Вывести факультет и связные кафедры
SELECT 
    f.id AS faculty_id, 
    f.name AS faculty_name, 
    f.dean_name, 
    d.id AS department_id, 
    d.name AS department_name
FROM faculty AS f
LEFT JOIN department AS d
    ON d.faculty_id = f.id
WHERE f.name = N'Факультет экономики и информационных технологий';


-- 3.2. Список специальностей и групп для них
SELECT 
    s.id AS specialty_id,
    s.name AS specialty_name,
    s.code AS specialty_code,
    g.id AS group_id,
    g.name AS group_name,
    g.course
FROM specialty AS s
LEFT JOIN edu_group AS g
    ON g.specialty_id = s.id
WHERE s.id IN (1,2,3,4,5)
ORDER BY s.id, g.course, g.name;


-- 3.3. Список студентов (несколько первых)
SELECT 
    st.id AS student_pk,
    st.full_name,
    st.student_id,
    g.name AS group_name,
    g.course,
    st.status
FROM student AS st
JOIN edu_group AS g
    ON st.group_id = g.id
ORDER BY g.id, st.full_name;


-- 3.4. Список преподавателей по кафедрам
SELECT 
    t.id AS teacher_id,
    t.full_name,
    t.position,
    d.name AS department_name
FROM teacher AS t
JOIN department AS d
    ON t.department_id = d.id
ORDER BY d.id, t.full_name;


